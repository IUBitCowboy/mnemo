#!/bin/bash

# A script to generate a standardized repository for storing and managing
# the artifacts created by a Course Developer Gem.

# --- Configuration ---
# This script is controlled by environment variables.
# Ensure the following are set before running:
#
# COURSE_ID: A short, script-friendly name for the course (e.g., "CybSec_201").
# COURSE_NAME: The full, human-readable name of the course (e.g., "Introduction to Cybersecurity").
# PRIMARY_ARTIFACT_TYPE: The main type of hands-on activity (e.g., "Exercises", "Labs", "Projects").
# PRIMARY_TOOL: The main software tool students will use (e.g., "the command line", "a C compiler").

# --- Validation ---
# Check if the required environment variables are set.
if [ -z "$COURSE_ID" ] || [ -z "$COURSE_NAME" ] || [ -z "$PRIMARY_ARTIFACT_TYPE" ] || [ -z "$PRIMARY_TOOL" ]; then
  echo "❌ Error: One or more required environment variables are not set."
  echo "Please set COURSE_ID, COURSE_NAME, PRIMARY_ARTIFACT_TYPE, and PRIMARY_TOOL."
  exit 1
fi

# --- Directory Creation ---
REPO_DIR="${COURSE_ID}_Artifacts"
mkdir -p "$REPO_DIR"
cd "$REPO_DIR"

echo "✅ Created root directory: $REPO_DIR"

# === Root Level Files ===
cat << EOF > README.md
# $COURSE_NAME - Course Artifacts

## 1. Purpose and Intent

This repository contains all the instructional materials (lectures, exercises, assignments, etc.) for the **$COURSE_NAME** course. These artifacts are generated by the **${COURSE_ID}_Gem** and are managed here under version control.

The goal is to maintain a clear, organized, and versioned history of all materials provided to students throughout the semester.

## 2. Repository Structure

* **/lectures:** Contains the Markdown content for all slide decks.
* **/$PRIMARY_ARTIFACT_TYPE:** Contains all hands-on student activities.
* **/assignments:** Contains formal, graded assignments.
* **/quizzes:** Contains materials for quizzes and assessments.
EOF

# Create a standard .gitignore
cat << EOF > .gitignore
# General
.DS_Store
*.swp
*~

# Python
__pycache__/
*.pyc

# IDEs
.vscode/
.idea/
EOF

# === Subdirectories ===
DIRECTORIES=("lectures" "$PRIMARY_ARTIFACT_TYPE" "assignments" "quizzes")

for DIR_NAME in "\${DIRECTORIES[@]}"; do
    mkdir -p "\$DIR_NAME"
    # Create a README in each subdirectory
    case "\$DIR_NAME" in
        "lectures")
            cat << EOF > "\$DIR_NAME"/README.md
# Lectures

This directory contains the Markdown source for all lecture slide decks. Each file represents the content for a single lecture.

## Examples of Files
* \`week01_lecture01_http_and_frameworks.md\`
* \`week02_lecture02_database_migrations.md\`
EOF
            ;;
        "$PRIMARY_ARTIFACT_TYPE")
            cat << EOF > "\$DIR_NAME"/README.md
# $PRIMARY_ARTIFACT_TYPE

This directory contains all the hands-on $PRIMARY_ARTIFACT_TYPE for the course. These are the primary activities students will use to practice their skills with **$PRIMARY_TOOL**.

## Examples of Files
* \`exercise01_intro_to_nmap.md\`
* \`exercise02_sql_injection.md\`
EOF
            ;;
        "assignments")
            cat << EOF > "\$DIR_NAME"/README.md
# Assignments

This directory contains the official, graded assignments for the course.

## Examples of Files
* \`assignment01_threat_model_analysis.md\`
* \`assignment02_final_incident_report.md\`
EOF
            ;;
        "quizzes")
            cat << EOF > "\$DIR_NAME"/README.md
# Quizzes

This directory contains the questions and materials for in-class or take-home quizzes.

## Examples of Files
* \`quiz01_networking_concepts.md\`
* \`quiz02_cryptography_basics.md\`
EOF
            ;;
    esac
done

echo "🎉 Course artifact repository for '$COURSE_NAME' created successfully!"
echo "Navigate to the '$REPO_DIR' directory to begin."